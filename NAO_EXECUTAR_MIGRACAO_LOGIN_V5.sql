V9.0 — TERRAL | CONTROLE DE OBRAS

O que mudou
- Login passou a ser corporativo: TERRAL | CONTROLE DE OBRAS.
- Após login, o usuário vê os 9 cards de obras.
- Todos os cards são visíveis.
- Somente obras liberadas para o usuário ficam acessíveis.
- Administrador tem acesso a todas as obras.
- Todos os usuários comuns já existentes recebem acesso inicial ao Emirates uma única vez.
- Emirates abre o sistema já existente.
- As outras obras já possuem rota e tela de “módulos em configuração”.
- As 9 imagens usadas nos cards são exatamente as imagens fornecidas para esta versão.
- Novo Worker name mantido como terral-controle-obras.
- Banco D1 continua sendo emirates-ponto-db e NÃO precisa ser recriado.
- Não é necessário executar SQL manualmente: projects, user_projects e system_meta são criadas automaticamente.

